export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in font pixels of a string (1px tracking). */
export function textWidth(text: string): number {
  return text.length ? text.length * (GLYPH_W + 1) - 1 : 0;
}

/**
 * Draw `text` at (x, y) top-left (or centred when align='center'), each font
 * pixel `scale` canvas pixels. Unknown characters render as blanks.
 */
export function drawText(
  g: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
  align: 'left' | 'center' | 'right' = 'left',
  shadow?: string,
) {
  const w = textWidth(text) * scale;
  let cx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  if (shadow) drawRaw(g, text, cx + scale, y + scale, scale, shadow);
  drawRaw(g, text, cx, y, scale, color);
}

function drawRaw(g: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string) {
  g.fillStyle = color;
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const rows = G[ch] ?? G[ch.toUpperCase()];
    if (rows) {
      for (let r = 0; r < GLYPH_H; r++) {
        const bits = rows[r];
        if (!bits) continue;
        for (let c = 0; c < GLYPH_W; c++) {
          if (bits & (1 << (GLYPH_W - 1 - c))) g.fillRect(cx + c * scale, y + r * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

/** Greedy word-wrap to at most `max` characters per line. */
export function wrapText(text: string, max: number): string[] {
  const words = text.split(' ');
  const out: string[] = [];
  let cur = '';
  for (const w of words) {
    if ((cur + ' ' + w).trim().length > max) {
      if (cur) out.push(cur);
      cur = w;
    } else cur = (cur + ' ' + w).trim();
  }
  if (cur) out.push(cur);
  return out;
}
